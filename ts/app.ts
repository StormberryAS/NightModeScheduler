/* NightModeScheduler Logic
   Offline evening screen-time log with a simple bedtime estimate. Logs are
   held in localStorage encrypted at rest with a device-bound, non-extractable
   AES-GCM key (see the ENCRYPTION AT REST block below).

   A classic script, not a module: index.html loads it at the end of the body,
   after gate.js (the first-run notice, generated by build-gates.py), and the
   two share nothing. This file has no import or export, so tsc compiles it to
   a plain script at the same path (app.js).
*/

/** One saved evening. The stored list may also hold entries from an import or an older
    version, so the code reads every entry as unknown and checks each field. */
interface LogEntry {
  /** Milliseconds since 1970, when the entry was saved. */
  timestamp: number;
  /** Hours of screen time after 18:00, from the slider. */
  hours: number;
  /** The estimate, minutes since midnight. Entries saved before 2026-10 do not have it. */
  bedtimeMinutes: number;
}

/** An element of the page. Every id below is in index.html; a missing one stops the script
    here, where the JavaScript before it failed on the first use of the element. */
function byId(id: string): HTMLElement {
  const el = document.getElementById(id);
  if (!el) throw new Error(`NightModeScheduler: #${id} is missing`);
  return el;
}

/** An input element of the page, the same way. */
function inputById(id: string): HTMLInputElement {
  const el = byId(id);
  if (!(el instanceof HTMLInputElement)) throw new Error(`NightModeScheduler: #${id} is not an input`);
  return el;
}

/** value[key], as JavaScript reads it: a TypeError for null and undefined, else the property
    (undefined when there is none). For data from JSON.parse, typed unknown. */
function prop(value: unknown, key: string): unknown {
  if (value === null || value === undefined) {
    throw new TypeError(`Cannot read properties of ${String(value)} (reading '${key}')`);
  }
  return (value as { readonly [key: string]: unknown })[key];
}

/** Array.isArray, typed for unknown data. */
function isArray(value: unknown): value is unknown[] {
  return Array.isArray(value);
}

